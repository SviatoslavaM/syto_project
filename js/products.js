function cleanProductText(value) {
  if (!value) return value;

  return value
    .replace(/\u00a0/g, ' ')
    .replace(/\s{2,}/g, ' ')
    .replace(/вищогосорту/g, 'вищого сорту')
    .replace(/сількухонна/g, 'сіль кухонна')
    .replace(/яйцякурячі/g, 'яйця курячі')
    .replace(/капустабілокачанна/g, 'капуста білокачанна')
    .replace(/сиркисломолочний/g, 'сир кисломолочний')
    .replace(/салосвинне/g, 'сало свинне')
    .replace(/масловершкове/g, 'масло вершкове')
    .replace(/–підкреслено/g, '– підкреслено')
    .replace(/\)в/g, ') в')
    .replace(/\)в\s*(\d+)/g, ') в $1')
    .replace(/прикiмнатній/g, 'при кімнатній')
    .replace(/вкиплячу/g, 'в киплячу')
    .replace(/Готовівареники/g, 'Готові вареники')
    .replace(/По\s*живна|П\s*оживна/g, 'Поживна')
    .replace(/Стро\s*к|Стр\s*ок/g, 'Строк')
    .replace(/Не\s*дозво\s*лено/g, 'Не дозволено')
    .replace(/\.(?=[А-ЯІЇЄҐ])/g, '. ')
    .replace(/,(?=[А-ЯІЇЄҐ])/g, ', ')
    .replace(/в\s*(\d+)г/g, 'в $1 г')
    .replace(/(\d+)гпродукту/g, '$1 г продукту')
    .replace(/\s+([,.;:])/g, '$1')
    .trim();
}

